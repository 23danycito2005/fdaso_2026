"""Recorrido funcional con Chromium. Ejecutar con el servidor de npm run dev activo."""
from pathlib import Path
import json, os
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
BASE = os.environ.get('PITOCUNA_TEST_URL', 'http://127.0.0.1:8766/?demo=1')
OUTPUT = ROOT/'test-results'
OUTPUT.mkdir(exist_ok=True)

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium')
    context=browser.new_context(viewport={'width':1440,'height':1000},accept_downloads=True)
    page=context.new_page()
    errors=[]
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('dialog', lambda dialog: dialog.accept())
    page.goto(BASE)
    expect(page.locator('h1')).to_have_text('Del cronograma al trabajo preparado')

    def nav(view,title):
        page.locator(f'nav a[href="#{view}"]').click()
        expect(page.locator('h1')).to_have_text(title)

    nav('lookahead','Lookahead · preparar el trabajo')
    row=page.locator('tr').filter(has=page.locator('[data-action="activity"][data-id="TU-01"]'))
    row.locator('[data-action="prepare"]').click()
    page.locator('form[data-form="preparation"] [name="reviewer"]').fill('Residente de prueba')
    page.locator('[name="note"]').fill('Recursos, frente y seguridad revisados para el escenario')
    for checkbox in page.locator('form[data-form="preparation"] input[type="checkbox"]').all(): checkbox.check()
    page.get_by_role('button',name='Confirmar preparación',exact=True).click()
    expect(page.locator('#modal')).not_to_be_visible()
    expect(row).to_contain_text('Preparada')
    nav('semanal','Plan semanal · comprometer y cumplir')
    page.locator('[data-action="new-plan"]').click()
    page.locator('[name="start"]').fill('2026-05-11')
    page.locator('[name="end"]').fill('2026-05-16')
    page.locator('#modal').get_by_role('button',name='Crear semana',exact=True).click()
    page.locator('[data-action="choose-commitment"]').click()
    page.locator('[name="activityId"]').select_option('TU-01')
    page.locator('[name="target"]').fill('100')
    page.locator('[name="criterion"]').fill('100 m instalados y revisados en T-01')
    page.get_by_role('button',name='Añadir al borrador semanal').click()
    page.locator('[data-action="freeze"]').click()
    expect(page.locator('#main')).to_contain_text('Plan congelado')
    page.locator('#cut-date').fill('2026-05-16')
    page.locator('#cut-date').dispatch_event('change')
    nav('avance','Avance y flujo por ubicación')
    page.locator('[data-action="progress"][data-id="TU-01"]').click()
    page.locator('[name="date"]').fill('2026-05-14')
    page.locator('[name="quantity"]').fill('100')
    page.locator('[name="evidence"]').fill('Registro de medición y revisión de prueba')
    page.locator('[name="reviewer"]').fill('Residente de prueba')
    page.locator('[name="accepted"]').check()
    page.get_by_role('button',name='Guardar avance',exact=True).click()
    expect(page.locator('#modal')).not_to_be_visible()
    page.locator('[data-action="interruption"][data-id="TU-01"]').click()
    page.locator('[name="start"]').fill('2026-05-12')
    page.locator('[name="end"]').fill('2026-05-13')
    page.locator('[name="cause"]').fill('Interrupción ficticia por lluvia')
    page.get_by_role('button',name='Registrar interrupción',exact=True).click()
    nav('semanal','Plan semanal · comprometer y cumplir')
    page.locator('[data-action="close-commitment"]').click()
    page.locator('[name="confirmed"]').check()
    page.get_by_role('button',name='Registrar resultado',exact=True).click()
    expect(page.locator('#main')).to_contain_text('100 %')
    nav('indicadores','Indicadores que se pueden reconstruir')
    expect(page.locator('.stat').filter(has_text='PPC').locator('strong')).to_have_text('100 %')
    expect(page.locator('.stat').filter(has_text='Continuidad').locator('strong')).to_have_text('50 %')
    page.reload()
    expect(page.locator('.stat').filter(has_text='PPC').locator('strong')).to_have_text('100 %')
    with page.expect_download() as event: page.locator('[data-action="backup"]').click()
    event.value.save_as(OUTPUT/'respaldo-recorrido.json')
    saved=json.loads((OUTPUT/'respaldo-recorrido.json').read_text())
    assert saved['plans'][0]['members'][0]['result']=='cumplido'
    assert len(saved['plans'][0]['members'])==1

    context.close()
    print('PASS: recorrido semanal, indicadores, persistencia y respaldo',flush=True)

    # Nuevo navegador: importar Excel auténtico con dos hojas y conservar la relación por partida–ubicación.
    imports=browser.new_context(viewport={'width':1440,'height':1000})
    tab=imports.new_page()
    tab.on('pageerror',lambda error: errors.append(str(error)))
    tab.on('dialog',lambda dialog:dialog.accept())
    tab.goto(BASE+'#datos')
    expect(tab.locator('h1')).to_have_text('Datos que alimentan el modelo')
    tab.locator('[data-action="import-schedule"]').click()
    tab.locator('#file-input').set_input_files(ROOT/'ejemplos/datos-ejemplo.xlsx')
    expect(tab.locator('#modal-title')).to_contain_text('datos-ejemplo.xlsx')
    expect(tab.locator('#modal-body')).to_contain_text('2 filas válidas')
    tab.locator('[data-action="confirm-import"]').click()
    expect(tab.locator('#modal')).not_to_be_visible()
    expect(tab.locator('#project-mode')).to_have_text('PROYECTO PROPIO')
    expect(tab.locator('.data-table tbody tr')).to_have_count(2)
    tab.locator('[data-data-tab="metrados"]').click()
    tab.locator('[data-action="import-measures"]').click()
    tab.locator('#file-input').set_input_files(ROOT/'ejemplos/datos-ejemplo.xlsx')
    expect(tab.locator('#import-sheet')).to_be_visible()
    tab.locator('#import-sheet').select_option(label='Metrados')
    expect(tab.locator('#modal-body')).to_contain_text('2 filas válidas')
    tab.locator('[data-action="confirm-import"]').click()
    expect(tab.locator('#modal')).not_to_be_visible()
    expect(tab.locator('.data-table tbody tr').first).to_contain_text('5 j')
    tab.reload()
    expect(tab.locator('#project-mode')).to_have_text('PROYECTO PROPIO')
    tab.locator('[data-data-tab="metrados"]').click()
    tab.locator('[data-action="measure-index"]').first.click()
    tab.locator('[name="rate"]').fill('10')
    tab.locator('#modal').get_by_role('button',name='Guardar',exact=True).click()
    expect(tab.locator('.data-table tbody tr').first).to_contain_text('10 j')
    tab.locator('[data-data-tab="cronograma"]').click()
    expect(tab.locator('.data-table tbody tr').first).to_contain_text('04/05/2026 → 08/05/2026')

    imports.close()
    print('PASS: Excel con dos hojas, enlace y persistencia',flush=True)

    # CSV y XML: cada archivo pasa por vista previa y no mezcla datos de demostración.
    csv_context=browser.new_context()
    csv_page=csv_context.new_page()
    csv_page.goto(BASE+'#datos')
    expect(csv_page.locator('h1')).to_have_text('Datos que alimentan el modelo')
    csv_page.locator('[data-action="import-schedule"]').click()
    csv_page.locator('#file-input').set_input_files(ROOT/'ejemplos/cronograma-ejemplo.csv')
    expect(csv_page.locator('#modal-body')).to_contain_text('2 filas válidas')
    csv_page.locator('[data-action="confirm-import"]').click()
    expect(csv_page.locator('.data-table tbody tr')).to_have_count(2)
    csv_context.close()
    print('PASS: CSV',flush=True)
    xml_context=browser.new_context()
    xml_page=xml_context.new_page()
    xml_page.on('pageerror',lambda error:errors.append(str(error)))
    xml_page.goto(BASE+'#datos')
    expect(xml_page.locator('h1')).to_have_text('Datos que alimentan el modelo')
    xml_page.locator('[data-action="import-schedule"]').click()
    xml_page.locator('#file-input').set_input_files(ROOT/'ejemplos/cronograma-ejemplo.xml')
    expect(xml_page.locator('#modal-body')).to_contain_text('2 filas válidas')
    expect(xml_page.locator('#modal-body')).to_contain_text('calendario XML no se aplica automáticamente')
    xml_page.locator('[data-action="confirm-import"]').click()
    expect(xml_page.locator('.data-table tbody tr')).to_have_count(2)
    expect(xml_page.locator('#main')).to_contain_text('Confirmar calendario de obra')

    xml_context.close()
    print('PASS: MS Project XML',flush=True)
    context=browser.new_context(viewport={'width':1440,'height':1000})
    page=context.new_page()
    page.on('pageerror',lambda error:errors.append(str(error)))

    # Aplicación y datos conservados tras una recarga sin conexión.
    page.goto(BASE+'#lookahead')
    expect(page.locator('h1')).to_have_text('Lookahead · preparar el trabajo')
    page.evaluate('navigator.serviceWorker.ready')
    page.wait_for_function('navigator.serviceWorker.controller !== null')
    context.set_offline(True)
    page.reload()
    expect(page.locator('h1')).to_have_text('Lookahead · preparar el trabajo')
    assert page.locator('.lookahead tbody tr').count()>0
    nav('datos','Datos que alimentan el modelo')
    page.locator('[data-action="import-schedule"]').click()
    page.locator('#file-input').set_input_files(ROOT/'ejemplos/datos-ejemplo.xlsx')
    expect(page.locator('#modal-body')).to_contain_text('2 filas válidas')
    page.locator('#modal').get_by_role('button',name='Cancelar',exact=True).click()
    context.set_offline(False)
    page.set_viewport_size({'width':390,'height':844})
    for view,title in [('datos','Datos que alimentan el modelo'),('lookahead','Lookahead · preparar el trabajo'),('restricciones','Liberación de restricciones'),('semanal','Plan semanal · comprometer y cumplir'),('avance','Avance y flujo por ubicación'),('indicadores','Indicadores que se pueden reconstruir')]:
        nav(view,title)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'),view
    page.screenshot(path=str(OUTPUT/'movil.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':1000})
    nav('lookahead','Lookahead · preparar el trabajo')
    page.screenshot(path=str(OUTPUT/'lookahead.png'),full_page=True)
    nav('datos','Datos que alimentan el modelo')
    page.screenshot(path=str(OUTPUT/'datos.png'),full_page=True)
    assert not errors, errors
    browser.close()
print('PASS: Excel / CSV / XML, preparación → compromiso → congelamiento → avance → PPC y continuidad, persistencia, respaldo, recarga sin conexión y seis secciones móviles.')
